<#
.SYNOPSIS
  Bundles the system name, logo, favicon and theme colour set under
  Settings in the NSales website into this app, then regenerates the
  launcher icons (from the favicon) and the app label (from the name).

.DESCRIPTION
  Reads the branding straight from the NSales database through
  `php artisan mobile:branding` in -NsalesPath. When that database is not
  running, it falls back to the live API (-ApiUrl)/branding.

  The app also loads the same branding live when it opens; this script is
  only needed for what Android/iOS bake into the install: the home-screen
  icon, the app name under it, and the logo shown before the first sync.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tool\sync_branding.ps1
  flutter build apk --release
#>
param(
    [string]$NsalesPath = 'D:\projects\nsales',
    [string]$ApiUrl = 'https://nsales.kemmytech.com/api/mobile'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$icons = Join-Path $root 'assets\icons'
New-Item -ItemType Directory -Force $icons | Out-Null

# Windows PowerShell's -Encoding utf8 adds a byte-order mark, which manifests and plists must not have.
function Write-Utf8NoBom([string]$path, [string]$text) {
    [System.IO.File]::WriteAllText($path, $text, (New-Object System.Text.UTF8Encoding $false))
}

function Get-BrandingFromDatabase {
    if (-not (Test-Path (Join-Path $NsalesPath 'artisan'))) { return $null }
    Push-Location $NsalesPath
    try {
        $out = & php artisan mobile:branding 2>$null
        if ($LASTEXITCODE -ne 0 -or -not $out) { return $null }
        return ($out -join "`n") | ConvertFrom-Json
    } catch {
        return $null
    } finally {
        Pop-Location
    }
}

function Save-Image([string]$localPath, [string]$url, [string]$target) {
    if ($localPath -and (Test-Path $localPath)) {
        Copy-Item $localPath $target -Force
        return "copied $localPath"
    }
    if ($url) {
        Invoke-WebRequest -Uri $url -OutFile $target -UseBasicParsing
        return "downloaded $url"
    }
    return $null
}

$brand = Get-BrandingFromDatabase
if ($brand) {
    Write-Host "Branding read from the database in $NsalesPath"
} else {
    Write-Host "Database not reachable; reading branding from $ApiUrl/branding"
    $brand = Invoke-RestMethod -Uri "$ApiUrl/branding" -Headers @{ Accept = 'application/json' }
}

$name = [string]$brand.site_name
if (-not $name) { $name = 'NSales' }
$color = [string]$brand.theme_primary
if ($color -notmatch '^#[0-9a-fA-F]{6}$') { $color = '#0f766e' }

# Logo: shown on the sign-in screen and as the fallback in app bars.
$logoNote = Save-Image $brand.logo_path $brand.logo_url (Join-Path $icons 'logo.png')
if ($logoNote) { Write-Host "Logo: $logoNote" } else { Write-Host 'Logo: none set, keeping the bundled logo' }

# Launcher icon: the favicon, or the logo when no favicon is set.
$iconTarget = Join-Path $icons 'app_icon.png'
$iconNote = Save-Image $brand.favicon_path $brand.favicon_url $iconTarget
if (-not $iconNote) { $iconNote = Save-Image $brand.logo_path $brand.logo_url $iconTarget }
if (-not $iconNote) { Copy-Item (Join-Path $icons 'logo.png') $iconTarget -Force; $iconNote = 'using the bundled logo' }
Write-Host "Launcher icon: $iconNote"

# Defaults compiled into the app (used until the live branding loads).
$dartName = $name.Replace('\', '\\').Replace("'", "\'").Replace('$', '\$')
$hex = $color.TrimStart('#').ToUpper()
$dart = @"
// Generated by tool/sync_branding.ps1 from the NSales Settings. Do not edit by hand.
import 'package:flutter/painting.dart';

const String kBrandName = '$dartName';
const Color kBrandPrimary = Color(0xFF$hex);
"@
Write-Utf8NoBom (Join-Path $root 'lib\core\brand_defaults.dart') ($dart + "`n")

# App name under the icon.
$xmlName = [System.Security.SecurityElement]::Escape($name)
$manifest = Join-Path $root 'android\app\src\main\AndroidManifest.xml'
Write-Utf8NoBom $manifest ((Get-Content $manifest -Raw -Encoding utf8) -replace 'android:label="[^"]*"', "android:label=`"$xmlName`"")
$plist = Join-Path $root 'ios\Runner\Info.plist'
if (Test-Path $plist) {
    Write-Utf8NoBom $plist ((Get-Content $plist -Raw -Encoding utf8) -replace '(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)', "`${1}$xmlName`${2}")
}
Write-Host "App name: $name   Theme colour: $color"

Push-Location $root
try {
    & dart run flutter_launcher_icons
    if ($LASTEXITCODE -ne 0) { throw 'flutter_launcher_icons failed' }
} finally {
    Pop-Location
}

Write-Host ''
Write-Host 'Done. Rebuild the app (flutter build apk --release) to ship the new icon and name.'
